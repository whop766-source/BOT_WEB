CREATE TABLE IF NOT EXISTS users(id BIGSERIAL PRIMARY KEY,name VARCHAR(120) NOT NULL,email VARCHAR(190) UNIQUE NOT NULL,password_hash TEXT NOT NULL,role VARCHAR(20) NOT NULL DEFAULT 'user' CHECK(role IN('user','admin')),balance NUMERIC(14,4) NOT NULL DEFAULT 0 CHECK(balance>=0),status VARCHAR(20) NOT NULL DEFAULT 'active',created_at TIMESTAMPTZ DEFAULT NOW());
CREATE TABLE IF NOT EXISTS providers(id BIGSERIAL PRIMARY KEY,name VARCHAR(120) NOT NULL,api_url TEXT NOT NULL,api_key TEXT NOT NULL,active BOOLEAN DEFAULT TRUE,created_at TIMESTAMPTZ DEFAULT NOW());
CREATE TABLE IF NOT EXISTS services(id BIGSERIAL PRIMARY KEY,provider_id BIGINT NOT NULL REFERENCES providers(id),provider_service_id VARCHAR(100) NOT NULL,category VARCHAR(120) NOT NULL,name VARCHAR(255) NOT NULL,description TEXT,cost_per_1000 NUMERIC(14,4) DEFAULT 0,price_per_1000 NUMERIC(14,4) NOT NULL,min_qty INTEGER DEFAULT 1,max_qty INTEGER DEFAULT 1000000,active BOOLEAN DEFAULT TRUE,created_at TIMESTAMPTZ DEFAULT NOW());
CREATE TABLE IF NOT EXISTS orders(id BIGSERIAL PRIMARY KEY,user_id BIGINT NOT NULL REFERENCES users(id),service_id BIGINT NOT NULL REFERENCES services(id),target_url TEXT NOT NULL,quantity INTEGER NOT NULL,charge NUMERIC(14,4) NOT NULL,provider_order_id VARCHAR(120),provider_status VARCHAR(80),status VARCHAR(20) NOT NULL DEFAULT 'pending',remains INTEGER,refunded NUMERIC(14,4) NOT NULL DEFAULT 0,last_sync_at TIMESTAMPTZ,created_at TIMESTAMPTZ DEFAULT NOW(),updated_at TIMESTAMPTZ DEFAULT NOW());
CREATE INDEX IF NOT EXISTS orders_sync_idx ON orders(status,last_sync_at);
CREATE TABLE IF NOT EXISTS transactions(id BIGSERIAL PRIMARY KEY,user_id BIGINT NOT NULL REFERENCES users(id),kind VARCHAR(20) NOT NULL,amount NUMERIC(14,4) NOT NULL,reference VARCHAR(190),note TEXT,created_at TIMESTAMPTZ DEFAULT NOW());
CREATE TABLE IF NOT EXISTS deposits(id BIGSERIAL PRIMARY KEY,user_id BIGINT NOT NULL REFERENCES users(id),method VARCHAR(30) DEFAULT 'manual',amount NUMERIC(14,4) NOT NULL,reference VARCHAR(190),status VARCHAR(20) DEFAULT 'pending',created_at TIMESTAMPTZ DEFAULT NOW());

CREATE TABLE IF NOT EXISTS campaign_packages(
  id BIGSERIAL PRIMARY KEY,
  name VARCHAR(160) NOT NULL,
  platform VARCHAR(80) NOT NULL DEFAULT 'Any',
  description TEXT,
  services JSONB NOT NULL DEFAULT '[]'::jsonb,
  default_duration_hours INTEGER NOT NULL DEFAULT 24 CHECK(default_duration_hours BETWEEN 1 AND 168),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS order_delivery_snapshots(
  id BIGSERIAL PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  delivered_units INTEGER NOT NULL CHECK(delivered_units >= 0),
  remains INTEGER,
  status VARCHAR(30) NOT NULL,
  source VARCHAR(30) NOT NULL DEFAULT 'provider',
  recorded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS delivery_snapshots_order_time_idx
  ON order_delivery_snapshots(order_id, recorded_at);
